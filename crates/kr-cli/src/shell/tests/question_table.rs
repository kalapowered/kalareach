                let verified = format!(
                    "n=$(cat '{0}' 2>/dev/null || echo 0); echo $((n + 1)) > '{0}'; \
             if [ \"$n\" = 0 ]; then printf kr-verified; else {1}; fi",
                    checks.display(),
                    stand.body
                );
                let body = the_right_answers(&ground.home);
                assert!(body.contains("printf kr-verified"), "{name}");
