/// The table, as the repository holds it.
const TABLE: &str = include_str!("../../../tests/shell_question_table.txt");

/// What the table says of a way whose answer is used.
const NOTHING: &str = "(nothing is said; the install goes on)";

/// The profile that the placement and the check are said behind, as the table has it. The walk's
/// home is read as `/home/person`.
const PROFILE: &str = "/home/person/profile.ps1";

const HEADER: &str = "\
# Generated by the lib case shell::tests::question_table::the_table_is_the_file of kr-cli. Make it again: KR_WRITE_QUESTION_TABLE=1 cargo test -p kr-cli --lib shell::tests::question_table::the_table_is_the_file (the case fails once after it writes; run it again without the variable).
# One row for each question that `kr shell install` asks PowerShell and each way that the question can end in: the whole text that the install says,
#   or what it does where the answer is used. A change of what the install says at the end of a question is a change of this file.
# questions: profiles (where PowerShell's two profiles are: said alone, because no profile is known yet), placement (where the entry goes in a profile)
#   and check (the check of the profile with the entry in it), the last two said behind the profile that they concern (here /home/person/profile.ps1).
# ways: used (the answer is read and understood), too_long (code 0 and an answer over the limit), not_text (code 0 and an answer that is not text),
#   wrong_form (code 0 and text that is not in the form that the question asked for), timed_out (the program did not end in time: it is ended and reaped),
#   not_started (the program could not be started), failed (a code other than 0), signalled (ended by a signal), wait_failed (this host could not wait for
#   the program: nothing is known of it, so nothing is read and it is not ended), not_prepared (this host could not prepare the call: its folder, the
#   file for the answer, a file for an input or one of the program's folders) and unread (code 0 and this host could not read the answer file). A
#   failure of this host (wait_failed, not_prepared, unread) names the path that failed and the system's error, with no profile in front of it, because
#   the profile is not what failed; `/tmp/kr-shell-ask-ID` is the call's folder and `/tmp/walk/pwsh` the program that this host could not wait for.
# what the install leaves: for each row the second section says what a failed question leaves: nothing written for PowerShell at the profile question,
#   the profile as it was at the other two, and that the install goes on where the answer is used. The walk makes every way but used and timed_out through
#   the install, each in a dry run and in a real run, and compares the home with what it was (at the profile question it also shows that no record is
#   written); a dry run shows that the install goes on for the used rows. The three timed_out rows are not made (the install gives each question sixty
#   seconds): their second cell is the rule that the install ends at the question that fails, before it writes for it, the same end that the walk shows
#   for every other way.
# outside the table: the answers that a script gives as refusals of the profile (`kr-refused <code>`), and a placement that is not inside the profile,
#   are answers that are used; each has its own sentence about the profile, and none depends on how a question ended. This file is made on Unix.
";

/// The questions, in the order of the table.
const QUESTIONS: [Question; 3] = [Question::Profiles, Question::Placement, Question::Check];

fn question_name(question: Question) -> &'static str {
    match question {
        Question::Profiles => "profiles",
        Question::Placement => "placement",
        Question::Check => "check",
    }
}

/// The profile that a question's failure is said behind: none for the question that asks where the
/// profiles are.
fn profile_of(question: Question) -> Option<&'static Path> {
    match question {
        Question::Profiles => None,
        Question::Placement | Question::Check => Some(Path::new(PROFILE)),
    }
}

/// The name of a way in the table.
fn way_name(way: &Ending<()>) -> &'static str {
    match way {
        Ending::Used(()) => "used",
        Ending::TooLong => "too_long",
        Ending::NotText => "not_text",
        Ending::WrongForm => "wrong_form",
        Ending::TimedOut => "timed_out",
        Ending::NotStarted => "not_started",
        Ending::Failed => "failed",
        Ending::Signalled => "signalled",
        Ending::WaitFailed(_) => "wait_failed",
        Ending::NotPrepared(_) => "not_prepared",
        Ending::Unread(_) => "unread",
    }
}

/// A failure of this host in `file`, as the table says one.
fn a_failure_of_this_host(file: &str, code: i32) -> HostFault {
    HostFault::new(PathBuf::from(file), std::io::Error::from_raw_os_error(code))
}

/// The way after `way`. A way added to the type is not compiled until it is placed here, so the
/// table cannot leave one out.
fn way_after(way: &Ending<()>) -> Option<Ending<()>> {
    Some(match way {
        Ending::Used(()) => Ending::TooLong,
        Ending::TooLong => Ending::NotText,
        Ending::NotText => Ending::WrongForm,
        Ending::WrongForm => Ending::TimedOut,
        Ending::TimedOut => Ending::NotStarted,
        Ending::NotStarted => Ending::Failed,
        Ending::Failed => Ending::Signalled,
        Ending::Signalled => Ending::WaitFailed(a_failure_of_this_host("/tmp/walk/pwsh", 10)),
        Ending::WaitFailed(_) => {
            Ending::NotPrepared(a_failure_of_this_host("/tmp/kr-shell-ask-ID", 20))
        }
        Ending::NotPrepared(_) => {
            Ending::Unread(a_failure_of_this_host("/tmp/kr-shell-ask-ID/said", 2))
        }
        Ending::Unread(_) => return None,
    })
}

/// Every way, in order.
fn every_way() -> Vec<Ending<()>> {
    let mut all = vec![Ending::Used(())];
    while let Some(next) = all.last().and_then(way_after) {
        all.push(next);
    }
    all
}

/// What the install says where `question` ended in `way`, from the one function that decides it and
/// the one that says it.
fn said_for(question: Question, way: Ending<()>) -> String {
    match conclude(question, way) {
        Ok(()) => NOTHING.to_owned(),
        Err(error) => super::super::startup_failure(profile_of(question), &error).to_string(),
    }
}

/// What the install leaves where `question` ended in `way`: nothing written for PowerShell at the
/// question that has no profile yet, the profile as it was at the others, and where the answer is
/// used the install goes on. The walk compares the home with what it was for every way that it makes,
/// which is every way but `used` and `timed_out`; the cell of `timed_out` is this rule alone.
fn left_after(question: Question, way: Ending<()>) -> &'static str {
    match (conclude(question, way), question) {
        (Ok(()), _) => "the install goes on",
        (Err(_), Question::Profiles) => "nothing written for PowerShell",
        (Err(_), Question::Placement | Question::Check) => "the profile as it was",
    }
}

/// The ways that the walk does not make through the install, with the reason.
const NOT_MADE: &[(&str, &str)] = &[(
    "timed_out",
    "the install gives each question sixty seconds, and each of the three would wait them; a case of kr-shell-integration \
         ends each question by a limit of 400 ms and compares the error with the one that this table's row comes from, \
         and a case there shows that the install gives each question more than the five seconds of a report; the second \
         cell of the three rows, what the install leaves, is the rule alone: no run of this walk waits the limit",
)];

/// The table, whole.
fn the_table() -> String {
    let mut out = String::from(HEADER);
    out.push_str("\n## what the install says\n");
    for question in QUESTIONS {
        for way in every_way() {
            let name = way_name(&way);
            out.push_str(&format!(
                "question={} way={name} -> {}\n",
                question_name(question),
                said_for(question, way)
            ));
        }
    }
    out.push_str("\n## what the install leaves\n");
    for question in QUESTIONS {
        for way in every_way() {
            let name = way_name(&way);
            out.push_str(&format!(
                "question={} way={name} -> {}\n",
                question_name(question),
                left_after(question, way)
            ));
        }
    }
    out.push_str("\n## the stand-ins of the walk, and the way that each makes\n");
    for stand in stands() {
        out.push_str(&format!(
            "question={} way={} stand-in={}\n",
            question_name(stand.question),
            stand.way,
            stand.state
        ));
    }
    out.push_str("\n## ways that the walk through the install does not make\n");
    for (way, why) in NOT_MADE {
        out.push_str(&format!("way={way}: {why}\n"));
    }
    out
}

/// Checks `made` against `held`: the variable writes the file, and the case then fails once.
fn is_the_file(made: &str, held: &str, file: &str, variable: &str) {
    let path = format!("{}/tests/{file}", env!("CARGO_MANIFEST_DIR"));
    if std::env::var_os(variable).is_some() {
        std::fs::write(&path, made).expect("the table is written");
        panic!("the table was written to {path}; build and run the case again without {variable}");
    }
    if made != held {
        let (made_lines, held_lines): (Vec<_>, Vec<_>) =
            (made.lines().collect(), held.lines().collect());
        let first = (0..made_lines.len().max(held_lines.len()))
            .find(|index| made_lines.get(*index) != held_lines.get(*index))
            .unwrap_or(0);
        panic!(
            "the table that the code makes differs from crates/kr-cli/tests/{file} from line {}:\n  file: {}\n  made: {}",
            first + 1,
            held_lines.get(first).unwrap_or(&"(none)"),
            made_lines.get(first).unwrap_or(&"(none)")
        );
    }
}

/// The table that the code makes is the table that the repository holds.
#[test]
fn the_table_is_the_file() {
    is_the_file(
        &the_table(),
        TABLE,
        "shell_question_table.txt",
        "KR_WRITE_QUESTION_TABLE",
    );
}

/// What the table says for `question` and the way named `way`.
fn cell(question: Question, way: &str) -> String {
    let key = format!("question={} way={way} -> ", question_name(question));
    TABLE
        .lines()
        .find_map(|line| line.strip_prefix(&key))
        .unwrap_or_else(|| panic!("the table has no row for {key}"))
        .to_owned()
}

/// A stand-in for PowerShell, a script of `sh`: what it does when the install asks it `question`.
struct Stand {
    question: Question,
    /// The way that it makes, as the table names it.
    way: &'static str,
    /// What of the way it makes, for the table.
    state: &'static str,
    /// What the script does.
    body: String,
}

fn stand(question: Question, way: &'static str, state: &'static str, body: &str) -> Stand {
    Stand {
        question,
        way,
        state,
        body: body.to_owned(),
    }
}

/// The stand-ins of the walk, which the install is asked through: each says what the question sees
/// of a PowerShell that ended in the way.
